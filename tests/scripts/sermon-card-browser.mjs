import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:4198';
assert.equal(new URL(base).hostname, '127.0.0.1');
const out = process.env.EVIDENCE_DIR || new URL('../../evidence/sermon-card/', import.meta.url).pathname;
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const checks = [], errors = [];
try {
  for (const width of [320, 390, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: width === 320 ? 720 : 844 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
    const writes = [];
    await context.route('**/*', async route => {
      const request = route.request(), url = new URL(request.url());
      if (url.origin !== base) return route.abort();
      if (!url.pathname.startsWith('/api/')) return route.continue();
      if (request.method() !== 'GET') writes.push({ url: url.pathname, method: request.method() });
      const data = url.pathname === '/api/status' ? { enabled: true, resources: [
        { id: 'space.songrim.access', category: 'space', label: '송림 입장 단계', state: 'hall_open', version: 1, updatedAt: '2026-10-05T03:00:00Z' },
      ] } : { enabled: true, items: [], photoCountToday: 0, today: '2026-10-05' };
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify(data) });
    });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install({ time: new Date('2026-10-05T12:00:00+09:00') });
    await page.clock.pauseAt(new Date('2026-10-05T12:00:00+09:00'));
    await page.goto(base);
    const card = page.locator('#tc-sermon-card');
    await card.getByRole('heading', { name: '하나님이 보시는 중심' }).waitFor();
    await page.screenshot({ path: out + `home-${width}.png` });
    assert.equal(await page.getByRole('tab').count(), 5);
    assert.equal(await page.locator('body').evaluate(e => e.scrollWidth <= innerWidth), true);
    assert.equal(await page.locator('.tc-sermon__questions').getAttribute('open'), null);
    const size = await page.getByRole('button', { name: '10월 5일 말씀 묵상' }).boundingBox();
    assert.ok(size.width >= 44 && size.height >= 44, JSON.stringify(size));
    await page.locator('.tc-journey').screenshot({ path: out + `dates-${width}.png` });
    await page.getByRole('button', { name: '10월 5일 말씀 묵상' }).focus();
    await page.keyboard.press('Enter');
    await page.clock.runFor(20);
    assert.equal(await card.evaluate(e => e === document.activeElement), true);
    await page.screenshot({ path: out + `card-${width}.png` });
    await card.screenshot({ path: out + `card-detail-${width}.png` });
    await card.getByText('말씀에서 나눈 기도 제목').click();
    assert.equal(await card.locator('.tc-sermon__prayer-excerpt').isVisible(), true);
    assert.equal(await card.getByRole('link', { name: /말씀 38:46–38:54/ }).getAttribute('href'), 'https://www.youtube.com/watch?v=0e11fIrc_6s&t=2326s');
    assert.equal(await card.getByText('오늘 하나님께 먼저 여쭙고 싶은 일은 무엇인가요?').count(), 0);
    assert.equal(await card.getByText('학교·집·일터에서 하나님을 사랑하고 신뢰하는 마음으로 할 수 있는 작은 일은 무엇인가요?').count(), 0);
    await card.screenshot({ path: out + `questions-${width}.png` });
    await page.getByRole('button', { name: '10월 6일 말씀 미등록' }).click();
    await card.getByRole('heading', { name: '아직 등록된 말씀이 없어요' }).waitFor();
    assert.equal(await card.getByRole('link').count(), 0);
    await page.getByRole('button', { name: '10월 5일 말씀 묵상' }).click();
    await card.getByRole('button', { name: '이 말씀으로 1분 기도하기' }).click();
    assert.equal(await page.getByRole('button', { name: '기도 시작', exact: true }).isVisible(), true);
    assert.match(await page.getByRole('timer').innerText(), /01:00/);
    await page.getByLabel('기도 시간', { exact: true }).selectOption('3');
    await page.getByRole('button', { name: '기도 시작', exact: true }).click();
    await page.clock.runFor(15000);
    await page.getByRole('tab', { name: '예배', exact: true }).click();
    await card.getByRole('button', { name: '이 말씀으로 1분 기도하기' }).click();
    assert.match(await page.getByRole('timer').innerText(), /02:45/);
    await page.getByRole('button', { name: '일시정지' }).click();
    await page.getByRole('button', { name: '말씀으로 돌아가기' }).click();
    await card.waitFor({ state: 'visible' });
    await card.getByRole('button', { name: '이 말씀으로 1분 기도하기' }).click();
    assert.match(await page.getByRole('timer').innerText(), /02:45/);
    await page.getByRole('button', { name: '이어서 기도' }).waitFor();
    await page.screenshot({ path: out + `timer-preserved-${width}.png` });
    await page.goBack();
    await card.waitFor({ state: 'visible' });
    await card.getByRole('button', { name: '내 기도제목 적기' }).click();
    const draft = page.getByLabel('어떤 마음으로 기도하고 있나요?');
    await draft.fill('합성 테스트: 일상에서 하나님께 먼저 여쭙게 해주세요.');
    const consent = page.getByRole('checkbox', { name: '함께 나누기 · 공개' });
    await consent.uncheck();
    await page.getByRole('button', { name: /입력 내용 미리보기/ }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('button', { name: '닫기', exact: true }).click();
    assert.match(await draft.inputValue(), /합성 테스트/);
    await page.getByRole('button', { name: /입력 내용 미리보기/ }).click();
    await page.goBack();
    await card.waitFor({ state: 'visible' });
    assert.equal(await page.getByRole('dialog').count(), 0);
    await page.goForward();
    await draft.waitFor();
    await page.clock.runFor(20);
    assert.match(await draft.inputValue(), /합성 테스트/);
    assert.equal(await consent.isChecked(), false);
    await page.locator('#tc-panel-prayer form').screenshot({ path: out + `draft-preserved-${width}.png` });
    await page.goBack();
    await card.waitFor({ state: 'visible' });
    await context.setOffline(true);
    assert.equal(await card.getByText('하나님을 사랑하는 마음').isVisible(), true);
    assert.deepEqual(writes, []);
    assert.equal(await page.locator('body').evaluate(e => e.scrollWidth <= innerWidth), true);
    checks.push({ width, noOverflow: true, dateTouchTarget: size, timerPreserved: '02:45 paused, selected 3 minutes', draftConsentPreserved: true, browserBackForward: true, previewCancel: true, offlineReflection: true, networkWrites: writes.length });
    await context.close();
  }
  assert.deepEqual(errors, []);
  await writeFile(out + 'browser-results.json', JSON.stringify({ checks, errors, data: 'Synthetic local fixtures only; external traffic blocked' }, null, 2));
  console.log('PASS: 320, 390, 1440px; timer/draft/consent/back/forward/cancel/offline; zero writes');
} finally { await browser.close(); }
