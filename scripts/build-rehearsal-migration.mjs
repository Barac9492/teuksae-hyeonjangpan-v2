import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const dir = path.join(root, 'supabase/migrations');
const files = (await readdir(dir)).filter(f => /^00[2-8]_.*\.sql$/.test(f)).sort();
if (files.length !== 7) throw new Error('Expected exactly migrations 002 through 008');
const shared = "perform pg_catalog.pg_advisory_xact_lock_shared(pg_catalog.hashtextextended('rehearsal-global-reset', 0));";
let replay = '';
for (const file of files) {
  let sql = await readFile(path.join(dir, file), 'utf8');
  sql = sql.replace(/^\s*(begin|commit);\s*$/gmi, '')
    .replaceAll('ops_', 'rehearsal_ops_')
    .replaceAll('community_v2', 'rehearsal_community_v2')
    .replaceAll('community-photos-v2', 'rehearsal-community-photos-v2')
    .replaceAll('ops-account:', 'rehearsal-ops-account:')
    .replaceAll("'community:", "'rehearsal-community:")
    .replaceAll('hashtextextended(p_request_id::text, 0)', "hashtextextended('rehearsal-request:' || p_request_id::text, 0)");
  // Every PL/pgSQL entry acquires the shared lock BEFORE any other lock.
  // SQL-language functions are read-only; the obsolete 002 revoke is replaced by 003.
  sql = sql.replace(/(language plpgsql[^$]*\$\$)([\s\S]*?)(\$\$;)/gi, (_, head, body, tail) => {
    if (!/\bbegin\b/i.test(body)) throw new Error(`Missing function BEGIN: ${file}`);
    return head + body.replace(/\bbegin\b/i, `begin\n  ${shared}`) + tail;
  });
  replay += `\n-- Replay ${file}\n${sql}\n`;
}
const output = `-- GENERATED by scripts/build-rehearsal-migration.mjs. Do not hand-edit.
-- Root companion rehearsal only. Legacy migration 001 is intentionally excluded.
-- Atomic, one-time install: never refresh live credentials or copy live activity.
begin;
do $guard$ begin
 if exists(select 1 from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid=c.relnamespace where n.nspname='public' and (c.relname like 'rehearsal\\_ops\\_%' escape '\\' or c.relname like 'rehearsal\\_community\\_v2%' escape '\\'))
 or exists(select 1 from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and (p.proname like 'rehearsal\\_ops\\_%' escape '\\' or p.proname like 'rehearsal\\_community\\_v2%' escape '\\'))
 or exists(select 1 from storage.buckets where id='rehearsal-community-photos-v2') then
  raise exception 'rehearsal already exists; refusing non-reentrant install';
 end if;
end; $guard$;
${replay}
-- Remove any bootstrap sample accounts before the ONE-TIME canonical copy.
delete from public.rehearsal_ops_accounts;
insert into public.rehearsal_ops_accounts(username,role,display_label,password_hash,active)
 select username,role,display_label,password_hash,active from public.ops_accounts;

create function public.rehearsal_ops_reset_rehearsal(p_session_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_username text; v_role text;
begin
 -- Global exclusive lock first: no mutation may cross a reset boundary.
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('rehearsal-global-reset', 0));
 select username into v_username from public.rehearsal_ops_sessions where id=p_session_id;
 if v_username is null then raise exception 'unauthorized' using errcode='42501'; end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('rehearsal-ops-account:' || v_username, 0));
 select a.role into v_role from public.rehearsal_ops_sessions s
 join public.rehearsal_ops_accounts a on a.username=s.username
 where s.id=p_session_id and s.username=v_username and s.revoked_at is null
 and s.expires_at>now() and a.active and a.credential_version=s.credential_version
 for update of s,a;
 if v_role is distinct from 'superadmin' then raise exception 'unauthorized' using errcode='42501'; end if;
 update public.rehearsal_ops_resources set state='checking',occupancy_percent=null,
 updated_at=null,last_closed_at=null,last_full_at=null,version=version+1;
 delete from public.rehearsal_ops_history;
 delete from public.rehearsal_ops_request_receipts;
 delete from public.rehearsal_community_v2_rates;
 delete from public.rehearsal_community_v2_audit;
 -- Keep path/token/payload tombstones indefinitely for late-upload cleanup and
 -- idempotent retries. Never remove storage.objects or return private paths.
 update public.rehearsal_community_v2_items set status='deleted',text='',event_day=null,
 ready=false,version=version+1,last_cleanup_at=null;
 return jsonb_build_object('reset',true);
end; $$;
revoke all on function public.rehearsal_ops_reset_rehearsal(uuid) from public,anon,authenticated;
grant execute on function public.rehearsal_ops_reset_rehearsal(uuid) to service_role;
commit;
`;
const target = path.join(dir, '009_rehearsal.sql');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('009_rehearsal.sql is stale');
  console.log('Rehearsal migration is reproducible');
} else {
  await writeFile(target, output);
  console.log(`Generated ${target}`);
}
